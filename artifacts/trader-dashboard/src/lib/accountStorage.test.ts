import assert from "node:assert/strict";
import { accountStorage } from "./accountStorage";
import { readRoutineDraft, routineDraftKey } from "./routineDraft";
import { appendRoutineCompletion, loadRoutineCompletions, saveMoodForDate, readMoodForDate } from "../pages/Routine.storage";
const values = new Map<string, string>();
const raw = { getItem: (key: string) => values.get(key) ?? null, setItem: (key: string, value: string) => { values.set(key, value); }, removeItem: (key: string) => { values.delete(key); } };
const a = accountStorage("a", raw)!, b = accountStorage("b", raw)!;
assert.equal(accountStorage(null, raw), undefined);
raw.setItem("tl_routine_completion_history_v1", JSON.stringify([{ id: "unowned" }]));
assert.deepEqual(loadRoutineCompletions(a), []);
assert.deepEqual(loadRoutineCompletions(), []);
const night = new Date("2026-10-01T22:30:00Z");
const record = appendRoutineCompletion({ routineId: "evening", routineTitle: "Evening", template: "evening", answers: { emotion: "calm" } }, a, night);
assert.equal(record.date, "2026-10-02");
assert.equal(loadRoutineCompletions(a).length, 1);
assert.equal(loadRoutineCompletions(b).length, 0);
saveMoodForDate("calm", night, a);
assert.equal(readMoodForDate(new Date("2026-10-02T07:00:00Z"), a), "calm");
assert.equal(readMoodForDate(night, b), null);
const key = routineDraftKey("evening");
a.setItem(key, JSON.stringify({ day: "2026-10-02", stepIdx: 4, answers: { emotion: "calm" } }));
assert.equal(readRoutineDraft(a, "evening", 7, night)?.stepIdx, 4);
assert.equal(readRoutineDraft(b, "evening", 7, night), null);
assert.equal(readRoutineDraft(a, "evening", 7, new Date("2026-10-02T22:30:00Z")), null);
a.setItem(key, '{"day":"2026-10-02","stepIdx":100,"answers":{}}');
assert.equal(readRoutineDraft(a, "evening", 7, night), null);
a.setItem(key, 'bad json');
assert.equal(readRoutineDraft(a, "evening", 7, night), null);
assert.ok(raw.getItem("tl_routine_completion_history_v1")?.includes("unowned"));
console.log("Account isolation, Rome day and routine draft recovery passed");
