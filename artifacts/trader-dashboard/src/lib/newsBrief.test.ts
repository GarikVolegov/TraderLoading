import assert from "node:assert/strict";
import { selectNewsBrief, newsArticleMatchesReference, newsArticleReference, newsRelevantToPair } from "./newsBrief";
const story = { title: "Fed decision", summary: "", source: "Federal Reserve", url: "https://www.federalreserve.gov/example", curationScore: 9 };
assert.equal(selectNewsBrief([{ ...story, curationScore: 7 }]).length, 0);
assert.equal(selectNewsBrief([story, { ...story, title: "Translated decision" }]).length, 1);
assert.equal(selectNewsBrief([{ ...story, isFallback: true }]).length, 0);
assert.equal(selectNewsBrief([{ ...story, freshnessTier: "fallback" }]).length, 0);
assert.equal(selectNewsBrief([{ ...story, url: "javascript:alert(1)" }]).length, 0);
assert.equal(selectNewsBrief([story, { ...story, curationScore: 12 }])[0].curationScore, 12);
assert.equal(selectNewsBrief([{ ...story, url: null }]).length, 0);
assert.equal(selectNewsBrief(Array.from({ length: 8 }, (_, i) => ({ ...story, url: `${story.url}/${i}`, curationScore: 8 + i }))).length, 5);
assert.equal(selectNewsBrief([{ ...story, curationScore: 10, url: `${story.url}/high` }, story])[0].curationScore, 10);
console.log("selected macro brief quality checks passed");
const event = { ...story, eventId: "event-fed", articleId: "document-a", resolvedUrl: "https://www.federalreserve.gov/resolved" };
assert.equal(newsArticleReference(event), "event-fed");
assert.equal(newsArticleMatchesReference(event, event.url), true);
assert.equal(newsArticleMatchesReference(event, event.resolvedUrl), true);
assert.equal(newsArticleMatchesReference(event, "document-a"), true);
assert.equal(newsArticleMatchesReference(event, "other-event"), false);
assert.equal(selectNewsBrief([event, { ...event, articleId: "document-b", url: "https://example.test/syndicated" }]).length, 1);
assert.equal(newsRelevantToPair({ ...story, affectedPairs: ["XAUUSD"] }, "EURUSD"), false);
assert.equal(newsRelevantToPair({ ...story, affectedPairs: ["XAUUSD"] }, "XAUUSD"), true);
assert.equal(newsRelevantToPair(story, null), true);
