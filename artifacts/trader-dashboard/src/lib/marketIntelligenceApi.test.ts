import assert from "node:assert/strict";
import { canDisplayProbabilities, decisionJournalHref, type DirectionalOutlook, type MarketDecision } from "./marketIntelligenceApi";
const now = Date.parse("2026-10-10T10:00:30Z");
const valid: DirectionalOutlook = { pair: "EURUSD", horizon: "4h", status: "available", reason: null, cutoffAt: "2026-10-10T10:00:00Z", issuedAt: "2026-10-10T10:00:05Z", targetEnd: "2026-10-10T14:00:00Z", referencePrice: 1.1, referenceObservedAt: "2026-10-10T10:00:00Z", neutralBand: { lower: 1.09, upper: 1.11 }, probabilities: { up: .4, flat: .35, down: .25 }, validation: { passed: true }, modelVersion: "validated-model", sources: ["dukascopy_bid"] };
assert.equal(canDisplayProbabilities(valid, "EURUSD", now), true);
assert.equal(canDisplayProbabilities(valid, "XAUUSD", now), false);
assert.equal(canDisplayProbabilities({ ...valid, status: "unvalidated" }, "EURUSD", now), false);
assert.equal(canDisplayProbabilities({ ...valid, validation: { passed: false } }, "EURUSD", now), false);
assert.equal(canDisplayProbabilities({ ...valid, validation: null }, "EURUSD", now), false);
assert.equal(canDisplayProbabilities({ ...valid, probabilities: { up: .9, flat: .35, down: .25 } }, "EURUSD", now), false);
assert.equal(canDisplayProbabilities({ ...valid, probabilities: { up: NaN, flat: .5, down: .5 } }, "EURUSD", now), false);
assert.equal(canDisplayProbabilities({ ...valid, referencePrice: null }, "EURUSD", now), false);
assert.equal(canDisplayProbabilities({ ...valid, issuedAt: "2026-10-10T09:58:00Z" }, "EURUSD", now), false);
assert.equal(canDisplayProbabilities({ ...valid, cutoffAt: "2026-10-10T10:01:00Z" }, "EURUSD", now), false);
assert.equal(canDisplayProbabilities({ ...valid, referenceObservedAt: "2026-10-10T09:50:00Z" }, "EURUSD", now), false);
assert.equal(canDisplayProbabilities({ ...valid, neutralBand: { lower: NaN, upper: 1.11 } }, "EURUSD", now), false);
assert.equal(canDisplayProbabilities({ ...valid, targetEnd: "2026-10-10T13:00:00Z" }, "EURUSD", now), false);
assert.equal(canDisplayProbabilities(valid, "EURUSD", now + 14400000), false);
const href = decisionJournalHref({ id: "saved-decision", snapshot: { pair: "XAUUSD" } } as MarketDecision);
const params = new URL(href, "https://example.test").searchParams;
assert.equal(params.get("marketDecisionId"), "saved-decision");
assert.equal(params.get("pair"), "XAUUSD");
assert.equal(params.get("horizon"), "4h");
assert.equal(params.has("entryPrice"), false);
assert.equal(params.has("stopLoss"), false);
console.log("probability display and journal context checks passed");
