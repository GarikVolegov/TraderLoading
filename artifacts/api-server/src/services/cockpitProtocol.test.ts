import assert from 'node:assert/strict';
import { freshCockpit, changeCockpit, cockpitRequirements, cockpitTriggers, cockpitWindow } from '../../../../contracts/cockpit.js';
import { cockpitAnalysisSchema, cockpitCalendarReason } from './cockpitProtocol.js';
const now=new Date('2026-10-19T07:15:00Z');
const full={...freshCockpit('EURUSD','scalp',now),cycle:'up' as const,context:'swept' as const,scenario:'valid_zone' as const,itfSchema:true,ltfSchema:true,trigger:'TEST' as const,area:'history' as const,target:'Asian high',targetConfirmed:true,news:'clear' as const,newsDay:'2026-10-19'};
assert.equal(cockpitAnalysisSchema.safeParse(full).success,true);
assert.deepEqual(cockpitRequirements(full,now),[]);
assert.ok(cockpitRequirements({...full,context:'compression'},now).length);
assert.ok(cockpitRequirements({...full,scenario:'no_zone'},now).some(s=>s.includes('trigger')));
assert.deepEqual(cockpitTriggers({...full,scenario:'reaccum'}),['JTC']);
assert.ok(cockpitRequirements({...full,area:'virgin'},now).some(s=>s.includes('sbilanciamento')));
assert.ok(cockpitRequirements({...full,news:'pre'},now).some(s=>s.includes('calendario')));
assert.ok(cockpitRequirements(full,new Date('2026-10-20T07:15:00Z')).some(s=>s.includes('giornata')));
const changed=changeCockpit(full,{market:'XAUUSD'});assert.equal(changed.cycle,'');assert.equal(changed.trigger,'');assert.equal(changed.news,'unchecked');
assert.equal(changeCockpit(full,{context:'intermediate'}).scenario,'');
assert.equal(changeCockpit(full,{itfSchema:false}).ltfSchema,false);
assert.equal(changeCockpit(full,{news:'post'}).ltfSchema,false,'post-news requires fresh schematic confirmations');
assert.equal(changeCockpit(full,{mode:'swing'}).targetConfirmed,false);
assert.equal(cockpitWindow(full,new Date('2026-10-19T16:01:00Z')).kind,'closed');
assert.equal(cockpitWindow({...full,mode:'swing'},new Date('2026-10-19T16:01:00Z')).kind,'open');
assert.equal(cockpitWindow(full,new Date('2026-10-17T08:00:00Z')).kind,'closed');
assert.equal(cockpitWindow(full,new Date('2026-10-26T07:15:00Z')).name,'Londra','Rome DST is applied');
assert.ok(cockpitCalendarReason([],['USD'],now));
assert.ok(cockpitCalendarReason([{date:'2026-10-12T09:00:00Z',country:'USD',impact:'High'}],['USD'],now));
assert.ok(cockpitCalendarReason([{date:'2026-10-19T07:20:00Z',country:'USD',impact:'High'}],['USD'],now));
assert.equal(cockpitCalendarReason([{date:'2026-10-19T09:00:00Z',country:'USD',impact:'High'}],['USD'],now),null);
assert.equal(cockpitAnalysisSchema.safeParse({...full,version:'unverified'}).success,false);
console.log('Cockpit protocol: scenario/trigger constraints, resets, day expiry, windows, DST and calendar guards passed');
