import assert from 'node:assert/strict';
import { createCotService, parseCotRows, type CotOutlook } from './cot.js';
import { cotForPair } from './cotContext.js';
const time=Date.parse('2026-09-24T12:00:00Z');
const row={market_and_exchange_names:'GOLD - COMMODITY EXCHANGE INC.',report_date_as_yyyy_mm_dd:'2026-09-15T00:00:00.000',noncomm_positions_long_all:'700',noncomm_positions_short_all:'300',comm_positions_long_all:'200',comm_positions_short_all:'500',nonrept_positions_long_all:'100',nonrept_positions_short_all:'200'};
const reports=parseCotRows([row,{...row,report_date_as_yyyy_mm_dd:'2026-09-08',noncomm_positions_long_all:'650'}, {...row,market_and_exchange_names:'MICRO GOLD - CME'}, {...row,noncomm_positions_short_all:null},{...row,report_date_as_yyyy_mm_dd:'2026-10-01'}],new Date(time).toISOString());
assert.equal(reports.length,1);assert.equal(reports[0].history.length,2);assert.equal(reports[0].nonCommNet,400);
assert.equal(reports[0].publishedAt,null,'never invent publication time from Tuesday observation');
const outlook:CotOutlook={reports,status:'available',source:'CFTC',fetchedAt:new Date(time).toISOString(),cached:false,fallback:false,nextUpdate:new Date(time).toISOString()};
assert.equal(cotForPair('XAUUSD',outlook,time).score,40);
assert.equal(cotForPair('BTCUSD',outlook,time).score,null);
assert.equal(cotForPair('XAUUSD',outlook,time+12*86400000).score,null);
assert.equal(cotForPair('XAUUSD',{...outlook,status:'stale'},time).score,null);
const fx={...outlook,reports:[{...reports[0],currency:'EUR'},{...reports[0],currency:'JPY',nonCommLong:300,nonCommShort:700}]};
assert.equal(cotForPair('EURUSD',fx,time).score,40);
assert.equal(cotForPair('USDJPY',fx,time).score,40);
assert.equal(cotForPair('EURJPY',fx,time).score,40);
assert.equal(cotForPair('EURGBP',fx,time).score,null,'both legs required for a cross');
assert.equal(cotForPair('EURJPY',{...fx,reports:[fx.reports[0],{...fx.reports[1],date:'2026-09-08'}]},time).score,null);
let now=time,fail=true,calls=0;
const get=createCotService(async()=>{calls++;if(fail)throw new Error('outage');return reports;},()=>now);
assert.equal((await get()).status,'unavailable');assert.deepEqual((await get()).reports,[]);assert.equal(calls,1);
now+=60001;fail=false;
const [a,b]=await Promise.all([get(),get()]);assert.equal(calls,2);assert.equal(a.status,'available');assert.deepEqual(a,b);
const original=a.fetchedAt;now+=3600001;fail=true;
const stale=await get();assert.equal(stale.status,'stale');assert.equal(stale.fetchedAt,original);assert.equal(stale.reports[0].status,'stale');assert.equal(stale.fallback,false);
now+=60001;fail=false;assert.equal((await get()).status,'available');
console.log('COT real-only parsing, exclusions, pair direction, cache failure and recovery passed');
