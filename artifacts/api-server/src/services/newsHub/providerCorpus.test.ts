import assert from "node:assert/strict";
import { articleFromBenzingaMessage, articleFromFinnhubMessage } from "./providerSockets.js";
import { newsSubscriptionKey, providerCandidates, queueProviderArticle } from "./providerCorpus.js";
import type { NewsArticle } from "./types.js";
assert.equal(articleFromBenzingaMessage({title:"Fed news without publication",updated_at:"2026-10-09T12:00:00Z"})?.publishedAt,null);
assert.equal(articleFromFinnhubMessage({data:[{headline:"Fed news without publication"}]})[0].publishedAt,null);
const now = Date.parse("2026-10-10T12:00:00Z");
const archived: NewsArticle[] = [];
const archive = async (articles: NewsArticle[]) => { archived.push(...articles); return articles; };
const article: NewsArticle = {title:"Fed announces a policy statement",summary:"Genuine source snippet",source:"TestWire",publishedAt:null,url:"https://example.test/provider-gates",sentiment:null,imageUrl:null};
assert.equal(queueProviderArticle(article,archive),true);
assert.equal(queueProviderArticle(article,archive),false);
assert.equal(providerCandidates(now).some(a=>a.url===article.url),false,"transport time is not publication time");
assert.equal(queueProviderArticle({...article,publishedAt:"2026-10-10T11:00:00Z"},archive),true,"same URL with corrected evidence is a new revision");
assert.equal(providerCandidates(now).some(a=>a.url===article.url),true);
await Promise.resolve();
assert.equal(archived.length,2,"raw undated evidence is archived before freshness gates");
assert.equal(newsSubscriptionKey({pairs:"EUR/USD,USDJPY,EURUSD",lang:"EN-us"}),"EURUSD,USDJPY:en");
assert.notEqual(newsSubscriptionKey({pairs:"EURUSD,GBPJPY",lang:"it"}),newsSubscriptionKey({pairs:"EURJPY,GBPUSD",lang:"it"}));
console.log("provider publication, revision, archive and subscription isolation checks passed");
